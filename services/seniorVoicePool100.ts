// 나이와 성별, 성향에 가장 잘 부합하는 100인 보이스 프로필 매칭 헬퍼
export function getMatchedSeniorVoice(age: number, gender: 'male' | 'female', behaviorType?: string): SeniorVoiceProfile {
  const targetGroup = age < 50 ? '40s' : age < 60 ? '50s' : age < 70 ? '60s' : '70s';
  const candidates = SENIOR_VOICE_POOL_100.filter(v => v.age_group === targetGroup && v.gender === gender);
  
  if (candidates.length === 0) {
    const genderCandidates = SENIOR_VOICE_POOL_100.filter(v => v.gender === gender);
    return genderCandidates[Math.floor(Math.random() * genderCandidates.length)] || SENIOR_VOICE_POOL_100[0];
  }

  if (behaviorType) {
    const traitMatched = candidates.filter(v => v.trait === behaviorType);
    if (traitMatched.length > 0) {
      return traitMatched[Math.floor(Math.random() * traitMatched.length)];
    }
  }

  return candidates[Math.floor(Math.random() * candidates.length)];
}
