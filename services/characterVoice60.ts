/**
 * 나이, 성별, 성향(행동 아키타입)을 기반으로 가장 자연스러운 60인 음성 캐릭터 1명을 정밀 매칭
 */
export function getMatchedCharacterVoice60(
  age: number,
  gender: 'male' | 'female',
  behaviorType?: string
): CharacterVoiceProfile {
  // 성별 필터
  const candidates = CHARACTER_VOICE_60.filter(c => c.gender === gender);

  // 성향별 특화 매칭 우선
  if (behaviorType === 'cold_skeptic') {
    const skeptic = candidates.find(c => c.traitTag.includes('출처추궁') || c.traitTag.includes('권위') || c.traitTag.includes('하이톤'));
    if (skeptic) return skeptic;
  } else if (behaviorType === 'storyteller') {
    const story = candidates.find(c => c.traitTag.includes('하소연') || c.traitTag.includes('신세한탄') || c.traitTag.includes('가장'));
    if (story) return story;
  } else if (behaviorType === 'rapid_inquirer') {
    const rapid = candidates.find(c => c.traitTag.includes('극속도') || c.traitTag.includes('재촉') || c.traitTag.includes('용건만'));
    if (rapid) return rapid;
  } else if (behaviorType === 'despairing') {
    const despair = candidates.find(c => c.traitTag.includes('불안') || c.traitTag.includes('한숨') || c.traitTag.includes('울먹임'));
    if (despair) return despair;
  }

  // 나이대 근접도 기반 매칭
  let bestMatch = candidates[0];
  let minDiff = 999;
  for (const c of candidates) {
    const diff = Math.abs(c.age - age);
    if (diff < minDiff) {
      minDiff = diff;
      bestMatch = c;
    }
  }

  return bestMatch;
}

/**
 * ID로 60인 보이스 조회 (e.g. 'C20')
 */
export function getCharacterVoice60ById(id: string): CharacterVoiceProfile | undefined {
  return CHARACTER_VOICE_60.find(c => c.id === id);
}
