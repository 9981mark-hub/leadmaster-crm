export const resolveFaqRoleKey = (
  role?: OrgRole | string | null,
  tier?: number | string | null
): StandardRoleKey => {
  if (role === 'owner') return 'owner';
  if (role === 'admin') {
    if (tier === 3 || tier === 'super') return 'general_admin';
    return 'team_admin';
  }
  return 'agent';
};

